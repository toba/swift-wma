internal import Foundation

/// The ASF object identifiers the tag reader and the demuxer match against.
///
/// A GUID sits in the file mixed-endian, so the sixteen bytes are compared as they lie rather than
/// parsed into fields.
enum ASFGUID {
    static let header = bytes(
        0x30, 0x26, 0xB2, 0x75, 0x8E, 0x66, 0xCF, 0x11,
        0xA6, 0xD9, 0x00, 0xAA, 0x00, 0x62, 0xCE, 0x6C)

    /// The object holding the data packets, which follows the Header Object in the file.
    static let data = bytes(
        0x36, 0x26, 0xB2, 0x75, 0x8E, 0x66, 0xCF, 0x11,
        0xA6, 0xD9, 0x00, 0xAA, 0x00, 0x62, 0xCE, 0x6C)

    static let fileProperties = bytes(
        0xA1, 0xDC, 0xAB, 0x8C, 0x47, 0xA9, 0xCF, 0x11,
        0x8E, 0xE4, 0x00, 0xC0, 0x0C, 0x20, 0x53, 0x65)

    static let streamProperties = bytes(
        0x91, 0x07, 0xDC, 0xB7, 0xB7, 0xA9, 0xCF, 0x11,
        0x8E, 0xE6, 0x00, 0xC0, 0x0C, 0x20, 0x53, 0x65)

    static let contentDescription = bytes(
        0x33, 0x26, 0xB2, 0x75, 0x8E, 0x66, 0xCF, 0x11,
        0xA6, 0xD9, 0x00, 0xAA, 0x00, 0x62, 0xCE, 0x6C)

    static let extendedContentDescription = bytes(
        0x40, 0xA4, 0xD0, 0xD2, 0x07, 0xE3, 0xD2, 0x11,
        0x97, 0xF0, 0x00, 0xA0, 0xC9, 0x5E, 0xA8, 0x50)

    /// The object that wraps the extended header objects, the Metadata Library among them.
    static let headerExtension = bytes(
        0xB5, 0x03, 0xBF, 0x5F, 0x2E, 0xA9, 0xCF, 0x11,
        0x8E, 0xE3, 0x00, 0xC0, 0x0C, 0x20, 0x53, 0x65)

    /// The named values whose length an Extended Content Description cannot state, such as a cover
    /// past 64 KB.
    static let metadataLibrary = bytes(
        0x94, 0x1C, 0x23, 0x44, 0x98, 0x94, 0xD1, 0x49,
        0xA1, 0x41, 0x1D, 0x13, 0x4E, 0x45, 0x70, 0x54)

    /// The object a writer grows and shrinks so the header keeps its size and the data never moves.
    static let padding = bytes(
        0x74, 0xD4, 0x06, 0x18, 0xDF, 0xCA, 0x09, 0x45,
        0xA4, 0xBA, 0x9A, 0xAB, 0xCB, 0x96, 0xAA, 0xE8)

    static let audioMedia = bytes(
        0x40, 0x9E, 0x69, 0xF8, 0x4D, 0x5B, 0xCF, 0x11,
        0xA8, 0xFD, 0x00, 0x80, 0x5F, 0x5C, 0x44, 0x2B)

    /// An object writes its identifier and its total length in front of its body.
    static let objectHeaderWidth = 24

    private static func bytes(_ values: UInt8...) -> Data { Data(values) }
}
